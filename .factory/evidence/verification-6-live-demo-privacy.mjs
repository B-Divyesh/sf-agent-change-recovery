import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext();
const page = await context.newPage();
const urls = [];
const errors = [];
page.on('request', request => urls.push(request.url()));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
page.on('pageerror', error => errors.push(error.message));
await page.goto('https://agent-change-recovery.sociobot.in/demo', { waitUntil: 'networkidle' });
await page.getByLabel('src/editor/autosave.ts').check();
await page.getByRole('button', { name: 'Export selected patch' }).click();
await page.getByRole('button', { name: 'Reverse 2 selected files' }).click();
await page.getByRole('button', { name: 'Create checkpoint and reverse' }).click();
const keysBeforeReset = await page.evaluate(() => Object.keys(localStorage));
await page.getByRole('button', { name: 'Reset demo' }).click();
const keysAfterReset = await page.evaluate(() => Object.keys(localStorage));
console.log(JSON.stringify({ urls, origins: [...new Set(urls.map(url => new URL(url).origin))], keysBeforeReset, keysAfterReset, errors }, null, 2));
await browser.close();
